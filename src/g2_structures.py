def _frozen_core_electrons(Z: int, uses_ecp: bool) -> int:
    """
    Frozen electrons per atom for ECP/frozen-core counting.

    Rules (when uses_ecp=True):
      - H–He (Z <= 2): 0 frozen
      - Li–Ne (3 <= Z <= 10): 2 frozen
      - Na (Z == 11): 2 frozen  [TEMPORARY: He-core ECP for Na]
      - above Na (Z >= 12): 10 frozen

    When uses_ecp is False: 0 frozen for all Z.
    """
    if not uses_ecp:
        return 0
    if Z <= 2:
        return 0
    if Z <= 11:        # TEMPORARY: includes Na (Z=11) → He-core ECP
        return 2
    return 10


class G2Geometry(object):
    """
    Container for a G2-like molecular geometry.

    Attributes
    ----------
    name : str
    symbols : list[str]
    coords_bohr : np.ndarray (natoms, 3)
    charge : int
    multiplicity : int  (2S+1)
    uses_ecp : bool

    Properties
    ----------
    nelec : int         # explicit electrons (valence if uses_ecp=True)
    spin : int          # 2S
    nelec_up/down : int
    """

    __slots__ = ("name", "symbols", "coords_bohr",
                 "charge", "multiplicity", "uses_ecp")

    def __init__(
        self,
        name: str,
        symbols: List[str],
        coords_bohr: np.ndarray,
        charge: int = 0,
        multiplicity: int = 1,
        uses_ecp: bool = True,
    ) -> None:
        self.name = name
        self.symbols = list(symbols)
        self.coords_bohr = np.array(coords_bohr, dtype=float, copy=True)
        self.charge = int(charge)
        self.multiplicity = int(multiplicity)
        self.uses_ecp = bool(uses_ecp)

    # ---- core helpers ----

    def _total_electrons_explicit(self) -> int:
        total = 0
        for sym in self.symbols:
            try:
                Z = NUCLEAR_CHARGES[sym]
            except KeyError as e:
                raise ValueError(
                    f"Unknown element {e!s} in G2Geometry[{self.name!r}]"
                )
            total += Z - _frozen_core_electrons(Z, self.uses_ecp)
        return total - self.charge

    # ---- properties ----

    @property
    def nelec(self) -> int:
        return self._total_electrons_explicit()

    @property
    def spin(self) -> int:
        """2S = multiplicity - 1."""
        return self.multiplicity - 1

    def _check_spin_consistency(self) -> None:
        twoS = self.spin
        nelec = self.nelec
        if (nelec - twoS) % 2 != 0:
            raise ValueError(
                f"Inconsistent nelec={nelec} and multiplicity={self.multiplicity} "
                f"for {self.name}: cannot get integer n_up/n_down."
            )

    @property
    def nelec_up(self) -> int:
        self._check_spin_consistency()
        return (self.nelec + self.spin) // 2

    @property
    def nelec_down(self) -> int:
        self._check_spin_consistency()
        return (self.nelec - self.spin) // 2

    # ---- mapping-like API for backwards compatibility ----

    def __getitem__(self, key: str) -> Any:
        if key == "symbols":
            return self.symbols
        if key == "coords_bohr":
            return self.coords_bohr
        if key == "charge":
            return self.charge
        if key == "multiplicity":
            return self.multiplicity
        if key == "uses_ecp":
            return self.uses_ecp
        if key == "nelec":
            return self.nelec
        if key == "nelec_up":
            return self.nelec_up
        if key == "nelec_down":
            return self.nelec_down
        raise KeyError(key)

    def get(self, key: str, default: Any = None) -> Any:
        try:
            return self[key]
        except KeyError:
            return default


